    private static func featuredCharacterIDs(for chapterNumber: Int) -> [Int] {
        guard (7...65).contains(chapterNumber) else { return [] }
        var ids = Array(6..<100).filter { id in
            7 + (id - 6) % 59 == chapterNumber
        }
        // 九十九菫は正体を明かす第57章にも明示して登場する。
        if chapterNumber == 57, !ids.contains(58) {
            ids.append(58)
        }
        return ids.sorted()
