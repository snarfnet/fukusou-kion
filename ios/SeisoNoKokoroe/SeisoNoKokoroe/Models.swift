        for scene in scenes {
            for target in scene.targets {
                for fact in scene.facts {
                    for action in scene.actions {
                        for angle in angles {
                            let index = result.count
                            result.append(
                                CleaningTip(
                                    id: index + 1,
                                    category: scene.name,
                                    target: target,
                                    title: "\(target)は「\(action)」から",
                                    body: "\(scene.name)の\(target)は、\(fact)。今日は\(action)だけで十分です。\(angle)。",
